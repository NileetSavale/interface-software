"""The pixel surface on an app we didn't write: ParaBank, read from screenshots only (evidence/parabank-pixels/).

    uv run python scripts/parabank_pixels.py     # needs the network and ANTHROPIC_API_KEY; about $0.05-0.10

The same public demo bank as evidence/parabank/, but driven by VisionSurface: the page is a picture, read by OCR,
acted on by mouse and keyboard; nothing is read from the HTML. The mock GUI was built to the surface's conventions;
this is the test of those conventions on styling nobody designed for them. The browser's network gate still applies
(it reads no page), so every write path stays a refused commitPath. Registers a fresh fictional customer, has Claude
discover the account-balance capability from the OCR'd text, and replays it with no model.
"""
import asyncio
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from parabank_evidence import keep, label, cases  # noqa: E402
import parabank_evidence  # noqa: E402
from parabank_setup import BASE, CUSTOMER, register  # noqa: E402

from interface.artifact.io import dump_artifact, load_artifact  # noqa: E402
from interface.cli import load_dotenv  # noqa: E402
from interface.discovery.loop import discover  # noqa: E402
from interface.evidence import Audit  # noqa: E402
from interface.replay.executor import Replayer  # noqa: E402

OUT = ROOT / "evidence" / "parabank-pixels"
GOAL = ROOT / "goals" / "parabank_pixels_account_balance.json"


async def main():
    load_dotenv()
    parabank_evidence.OUT = OUT  # keep() copies runs into this folder
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    accounts = await register()
    first, second = accounts[0], accounts[1]
    outcome = await discover(json.loads(GOAL.read_text()), BASE, {"accountId": first}, out_dir=ROOT / "artifacts",
                             budget_usd=0.60)
    print(json.dumps({k: v for k, v in outcome.items() if k != "artifact"}), flush=True)
    keep("01-discovery-pixels", outcome["run_id"], "Real Claude discovery on ParaBank, from pixels only",
         f"{outcome.get('steps')} steps, ${outcome.get('cost_usd', 0):.3f}: {outcome['status']}"
         + (f" ({outcome.get('reason')})" if outcome.get("reason") else ""), outcome["status"])
    if outcome["status"] == "recorded":
        path = Path(outcome["artifact"])
        artifact = load_artifact(path).model_copy(update={"status": "approved"})
        path.write_text(dump_artifact(artifact))
        for name, inputs, title in (("02-replay-other-account", {"accountId": second}, "Replay, no model: another account"),
                                    ("03-replay-no-such-account", {"accountId": "99999"}, "An account that isn't there")):
            result = await Replayer(artifact, BASE, inputs, audit=Audit(OUT / ".audit.jsonl")).run()
            keep(name, result.run_id, title, "From pixels only, with no model.", label(result))
            print(name, label(result), getattr(result, "outputs", None) and sorted(result.outputs), flush=True)
    (OUT / ".audit.jsonl").unlink(missing_ok=True)
    (OUT / "results.json").write_text(json.dumps(cases, indent=2) + "\n")
    rows = "\n".join(f"| [`{c['dir']}`]({c['dir']}/) | {c['title']} | `{c['result']}` | {c['why']} |" for c in cases)
    (OUT / "README.md").write_text(f"""# The pixel surface on an app we didn't write: ParaBank

Generated by `uv run python scripts/parabank_pixels.py` against [ParaBank]({BASE}/index.htm), with a fictional
customer registered for the run. The page was a picture: read by OCR from screenshots, driven by mouse and keyboard,
nothing read from the HTML (the browser's network gate still refused every commit path). Claude discovered the
capability from the OCR'd text; the replays ran with no model.

| Folder | What it shows | Result | |
|---|---|---|---|
{rows}

The mock GUI was built to the surface's conventions; ParaBank wasn't, and three earlier attempts found what didn't
hold. Each is fixed and tested (docs/ARCHITECTURE.md, "pixels only", ParaBank):

- **Select-all is Cmd+A in a macOS text field**, so a retried field was appended to: the password typed twice. The
  wrong password then landed in another customer's account on the public demo, whose number the model saw. Claude
  refused to accept an account it couldn't confirm. Fields are now cleared with the platform's select-all and
  Backspace; that attempt's evidence and log were deleted, never committed.
- **OCR reads password dots as text** ("FE00-00000000000"): a masked field is now a row of identical blobs, counted.
- **A bordered table read as one "button"**, its account number inside a name the masker never looks in: a box
  holding several lines of text is now a container.
- **Links**: blue or underlined text; values are re-read by their own role.
- **Labels above fields, and "Label: value" read as one word**: named from above; split at the gap after the colon,
  checked by reading the label alone.
- **A greeting with the customer's name, and bare account numbers, in a flat OCR snapshot**: two masker rules.
- **Positions in a list, and positions on screens with no screen code**: an element showing an input is found by
  that value (`{{{{inputs.accountId}}}}`), and a screen without a code gets no position strategies at all.

Values read from pixels on the other account matched ParaBank's own HTML (checked while fixing, not part of the
run). The data on a public demo resets, so this is evidence, not an eval.
""")
    forbidden = [CUSTOMER["firstName"], CUSTOMER["lastName"], CUSTOMER["ssn"], CUSTOMER["phoneNumber"],
                 CUSTOMER["address.street"], *accounts, os.environ["PARABANK_USER"], os.environ["PARABANK_PASSWORD"]]
    leaks = [f"{p.relative_to(ROOT)}: {v}" for p in OUT.rglob("*") if p.is_file()
             and p.suffix in {".jsonl", ".json", ".txt", ".md"} for v in forbidden if v in p.read_text()]
    if leaks:
        sys.exit("LEAKS:\n" + "\n".join(leaks))
    print(f"{len(cases)} cases in {OUT}; scan clean")


if __name__ == "__main__":
    asyncio.run(main())
